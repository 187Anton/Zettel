import AppKit

/// Read access to the clipboard (injectable for tests).
@MainActor
protocol PasteboardReading: AnyObject {
    var changeCount: Int { get }
    /// Plain text of the current contents, or `nil` for content that must not be
    /// collected (passwords from password managers, transient data).
    func collectableString() -> String?
}

@MainActor
final class SystemPasteboard: PasteboardReading {
    /// Conventions from nspasteboard.org, used by password managers.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    var changeCount: Int { NSPasteboard.general.changeCount }

    func collectableString() -> String? {
        let pasteboard = NSPasteboard.general
        if let types = pasteboard.types, !Self.ignoredTypes.isDisjoint(with: types) { return nil }
        return pasteboard.string(forType: .string)
    }
}

/// `paste` mode: while active, newly copied text is appended to one note.
///
/// macOS has no notification for clipboard changes, so the cheap `changeCount`
/// is checked once per second – only while the mode is active.
@MainActor
final class PasteCollector {
    static let didChange = Notification.Name("PasteCollectorDidChange")

    private let pasteboard: PasteboardReading
    private let scheduler: TickScheduler
    private var lastChangeCount = 0

    /// The note collecting, or `nil` when the mode is off.
    private(set) var noteID: String?
    /// Receives each new clipboard text with the target note id.
    var onCollect: ((_ noteID: String, _ text: String) -> Void)?

    init(pasteboard: PasteboardReading? = nil, scheduler: TickScheduler? = nil) {
        self.pasteboard = pasteboard ?? SystemPasteboard()
        self.scheduler = scheduler ?? RunLoopTickScheduler(disablesAppNap: false)
    }

    var isActive: Bool { noteID != nil }

    func isCollecting(into noteID: String) -> Bool { self.noteID == noteID }

    /// Starts collecting into a note. What is on the clipboard now is not taken.
    func start(noteID: String) {
        self.noteID = noteID
        lastChangeCount = pasteboard.changeCount
        scheduler.start { [weak self] in self?.tick() }
        NotificationCenter.default.post(name: Self.didChange, object: self)
    }

    func stop() {
        guard noteID != nil else { return }
        noteID = nil
        scheduler.stop()
        NotificationCenter.default.post(name: Self.didChange, object: self)
    }

    /// Zettel itself just wrote to the clipboard: do not collect that.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    func tick() {
        guard let noteID else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard let text = pasteboard.collectableString(),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        onCollect?(noteID, text)
    }

    /// Appends a collected text to note text: on a new line, trailing newlines removed.
    static func append(_ text: String, to note: String) -> String {
        let clean = text.trimmingCharacters(in: .newlines)
        if note.isEmpty { return clean }
        return note.hasSuffix("\n") ? note + clean : note + "\n" + clean
    }
}
